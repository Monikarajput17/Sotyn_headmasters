CREATE OR REPLACE VIEW attendance_foundation_conflicts AS
 SELECT 'duplicate_attendance_day'::text AS kind, user_id::text AS subject, date::text AS detail, count(*) AS records
 FROM attendance WHERE user_id IS NOT NULL GROUP BY user_id,date HAVING count(*)>1
 UNION ALL SELECT 'ambiguous_employee_login',user_id::text,''::text,count(*) FROM employees WHERE user_id IS NOT NULL GROUP BY user_id HAVING count(*)>1
 UNION ALL SELECT 'unlinked_employee',id::text,name::text,1::bigint FROM employees WHERE user_id IS NULL;

