 ('attendance'),('employees'),('payroll'),('attendance_capture'),('attendance_corrections'),
 ('attendance_locations'),('attendance_tracking'),('employee_shifts'),('employee_links'),('attendance_rules')
) AS m(module) WHERE r.name='Attendance foundation owner' ON CONFLICT(role_id,module) DO NOTHING;
