-- AT-01/02/03. Incremental, non-destructive. Never use the local baseline in production.
-- Hosted execution requires a reviewed owner: SET attendance.bootstrap_user_id = '<existing user id>';
-- Local setup may bootstrap ONLY the deliberately seeded local-admin in the marked local database.
CREATE TABLE IF NOT EXISTS attendance_permission_managers (
  user_id bigint PRIMARY KEY REFERENCES users(id), granted_at timestamptz NOT NULL DEFAULT now()
);
DO $$
DECLARE owner_id bigint;
BEGIN
  owner_id := nullif(current_setting('attendance.bootstrap_user_id', true), '')::bigint;
  IF owner_id IS NULL AND EXISTS (SELECT 1 FROM app_settings WHERE key='local_environment' AND value='sotyn-headmasters-local') THEN
    SELECT id INTO owner_id FROM users WHERE username='local-admin' AND active=1;
  END IF;
  IF owner_id IS NOT NULL THEN
    IF NOT EXISTS (SELECT 1 FROM users WHERE id=owner_id AND active=1 AND COALESCE(archived,0)=0) THEN
      RAISE EXCEPTION 'Bootstrap owner must be an existing active, nonarchived login';
    END IF;
    INSERT INTO attendance_permission_managers(user_id) VALUES(owner_id) ON CONFLICT DO NOTHING;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM attendance_permission_managers) THEN
    RAISE EXCEPTION 'Nominate and verify a permission owner with attendance.bootstrap_user_id before this migration';
  END IF;
END $$;

