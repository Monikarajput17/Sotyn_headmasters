INSERT INTO role_permissions(role_id,module,can_view,can_create,can_edit,can_delete,can_approve,can_see_all,scope_mode,scope_branches)
SELECT p.role_id,m.target,p.can_view,p.can_create,p.can_edit,p.can_delete,p.can_approve,p.can_see_all,p.scope_mode,p.scope_branches
FROM role_permissions p JOIN (VALUES
 ('attendance','attendance_capture'), ('attendance','attendance_corrections'),
 ('attendance','attendance_locations'), ('attendance','attendance_tracking'),
 ('employees','employee_shifts'), ('employees','employee_links'), ('payroll','attendance_rules')
) AS m(source,target) ON p.module=m.source
ON CONFLICT(role_id,module) DO NOTHING;

