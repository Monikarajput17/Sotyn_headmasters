// Chat migration: data/chat.db (separate SQLite file — "chat db and socket
// different", mam 2026-06-18) → the SAME Supabase Postgres as everything else.
// Post-migration the separation survives logically (chat tables are still
// their own tables, names denormalised, no joins to ERP tables) while the
// physical second DB file disappears.
//
// Creates chat_groups / chat_group_members / chat_messages / chat_reads (+
// indexes, + the is_dm / reply_to_id ALTER columns) and copies all rows.
// Re-runnable: truncates chat tables first. Usage:
//   node scripts/migrate-chat-to-supabase.js
require('dotenv').config();
const path = require('path');
const fs = require('fs');
const Database = require('better-sqlite3');
const { Client } = require('pg');

const CHAT_DB = path.join(__dirname, '..', 'data', 'chat.db');

const DDL = `
CREATE TABLE IF NOT EXISTS chat_groups (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL, created_by bigint, created_by_name text,
  created_at text DEFAULT to_char(now() at time zone 'utc', 'YYYY-MM-DD HH24:MI:SS'),
  is_dm bigint DEFAULT 0
);
CREATE TABLE IF NOT EXISTS chat_group_members (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  group_id bigint NOT NULL, user_id bigint NOT NULL, user_name text, added_by bigint,
  created_at text DEFAULT to_char(now() at time zone 'utc', 'YYYY-MM-DD HH24:MI:SS'),
  UNIQUE (group_id, user_id)
);
CREATE INDEX IF NOT EXISTS idx_cgm_group ON chat_group_members(group_id);
CREATE INDEX IF NOT EXISTS idx_cgm_user ON chat_group_members(user_id);
CREATE TABLE IF NOT EXISTS chat_messages (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  group_id bigint NOT NULL, body text, attachment_url text, attachment_name text,
  sender_id bigint, sender_name text,
  created_at text DEFAULT to_char(now() at time zone 'utc', 'YYYY-MM-DD HH24:MI:SS'),
  reply_to_id bigint
);
CREATE INDEX IF NOT EXISTS idx_cmsg_group ON chat_messages(group_id, created_at);
CREATE INDEX IF NOT EXISTS idx_cmsg_group_id ON chat_messages(group_id, id);
CREATE INDEX IF NOT EXISTS idx_cmsg_sender ON chat_messages(sender_id);
CREATE TABLE IF NOT EXISTS chat_reads (
  group_id bigint NOT NULL, user_id bigint NOT NULL, last_read_id bigint DEFAULT 0,
  updated_at text DEFAULT to_char(now() at time zone 'utc', 'YYYY-MM-DD HH24:MI:SS'),
  PRIMARY KEY (group_id, user_id)
);
`;

const TABLES = ['chat_groups', 'chat_group_members', 'chat_messages', 'chat_reads'];

(async () => {
  const pgc = new Client({ connectionString: process.env.DATABASE_URL, ssl: { rejectUnauthorized: false } });
  await pgc.connect();
  await pgc.query(DDL);
  console.log('chat tables ensured in Postgres');

  if (!fs.existsSync(CHAT_DB)) {
    console.log('no local chat.db — nothing to copy');
    await pgc.end();
    return;
  }
  const sq = new Database(CHAT_DB, { readonly: true });
  await pgc.query(`TRUNCATE ${TABLES.join(', ')} RESTART IDENTITY`);
  for (const table of TABLES) {
    let rows = [];
    try { rows = sq.prepare(`SELECT * FROM ${table}`).all(); } catch (_) { continue; }
    for (const row of rows) {
      const cols = Object.keys(row);
      await pgc.query(
        `INSERT INTO ${table} (${cols.join(',')}) VALUES (${cols.map((_, i) => '$' + (i + 1)).join(',')})`,
        cols.map((c) => row[c])
      );
    }
    console.log(`  ${table}: ${rows.length} rows`);
  }
  // realign identities
  for (const t of ['chat_groups', 'chat_group_members', 'chat_messages']) {
    await pgc.query(`SELECT setval(pg_get_serial_sequence('${t}','id'), COALESCE((SELECT MAX(id) FROM ${t}),0)+1, false)`);
  }
  console.log('chat data copied + sequences aligned');
  sq.close();
  await pgc.end();
})().catch((e) => { console.error('FATAL:', e.message); process.exit(1); });
