// Phase 1 of the Supabase migration: recreate the SQLite schema in Postgres.
//
// Reads the LIVE structure of data/erp.db via PRAGMAs (tables, columns,
// PKs, defaults, FKs, indexes) and emits equivalent Postgres DDL against
// DATABASE_URL. Idempotent-ish: pass --drop to wipe public schema first.
//
// Type-mapping philosophy: preserve app behaviour, not textbook types.
// The app was written against SQLite's loose typing (dates as text,
// booleans as 0/1 integers), so we map DATETIME/DATE -> text and
// BOOLEAN -> bigint. Tightening types is a later, deliberate step.
//
// Usage: node scripts/migrate-schema-to-supabase.js [--drop] [--dry-run]
require('dotenv').config();
const path = require('path');
const Database = require('better-sqlite3');
const { Client } = require('pg');

const SQLITE_PATH = path.join(__dirname, '..', 'data', 'erp.db');
const DRY = process.argv.includes('--dry-run');
const DROP = process.argv.includes('--drop');

const sq = new Database(SQLITE_PATH, { readonly: true });

function pgType(sqliteType) {
  const t = (sqliteType || '').toUpperCase();
  if (/INT/.test(t)) return 'bigint';
  if (/(REAL|FLOA|DOUB|NUMERIC|DECIMAL)/.test(t)) return 'double precision';
  if (/BLOB/.test(t)) return 'bytea';
  if (/BOOL/.test(t)) return 'bigint';
  return 'text'; // TEXT, CHAR, CLOB, DATETIME, DATE, and anything else
}

function q(name) {
  return '"' + String(name).toLowerCase().replace(/"/g, '""') + '"';
}

function pgDefault(dflt, type) {
  if (dflt === null || dflt === undefined) return null;
  const d = String(dflt).trim();
  if (/^CURRENT_TIMESTAMP$/i.test(d)) {
    // SQLite writes 'YYYY-MM-DD HH:MM:SS' (UTC) text; reproduce exactly.
    return "to_char(now() at time zone 'utc', 'YYYY-MM-DD HH24:MI:SS')";
  }
  if (/^(CURRENT_DATE|CURRENT_TIME)$/i.test(d)) {
    return d === 'CURRENT_DATE'
      ? "to_char(now() at time zone 'utc', 'YYYY-MM-DD')"
      : "to_char(now() at time zone 'utc', 'HH24:MI:SS')";
  }
  // Numeric literal into a text column needs quoting; pg is strict.
  if (type === 'text' && /^-?\d+(\.\d+)?$/.test(d)) return `'${d}'`;
  return d; // quoted strings and numbers pass through as-is
}

const tables = sq
  .prepare("SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name")
  .all()
  .map((r) => r.name);

const ddl = [];
const fkDdl = [];
const identityFix = [];

for (const table of tables) {
  const cols = sq.prepare(`PRAGMA table_info(${JSON.stringify(table)})`).all();
  const pkCols = cols.filter((c) => c.pk > 0).sort((a, b) => a.pk - b.pk);
  const singleIntPk =
    pkCols.length === 1 && /INT/i.test(pkCols[0].type || '');

  const lines = cols.map((c) => {
    const type = pgType(c.type);
    let line = `${q(c.name)} ${type}`;
    if (singleIntPk && c.pk === 1) {
      line += ' GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY';
      identityFix.push({ table, col: c.name });
      return line;
    }
    if (c.notnull) line += ' NOT NULL';
    const def = pgDefault(c.dflt_value, type);
    if (def !== null) line += ` DEFAULT ${def}`;
    return line;
  });

  if (!singleIntPk && pkCols.length) {
    lines.push(`PRIMARY KEY (${pkCols.map((c) => q(c.name)).join(', ')})`);
  }

  // UNIQUE constraints surface as auto-indexes; recreate the explicit ones below.
  ddl.push(`CREATE TABLE ${q(table)} (\n  ${lines.join(',\n  ')}\n);`);

  for (const fk of sq.prepare(`PRAGMA foreign_key_list(${JSON.stringify(table)})`).all()) {
    const onDel = fk.on_delete && fk.on_delete !== 'NO ACTION' ? ` ON DELETE ${fk.on_delete}` : '';
    const onUpd = fk.on_update && fk.on_update !== 'NO ACTION' ? ` ON UPDATE ${fk.on_update}` : '';
    fkDdl.push(
      `ALTER TABLE ${q(table)} ADD FOREIGN KEY (${q(fk.from)}) REFERENCES ${q(fk.table)} (${q(fk.to)})${onDel}${onUpd};`
    );
  }
}

// Indexes (explicit ones with SQL; skip sqlite autoindexes)
const idxDdl = [];
for (const { name, tbl_name } of sq
  .prepare("SELECT name, tbl_name FROM sqlite_master WHERE type='index' AND sql IS NOT NULL")
  .all()) {
  const info = sq.prepare(`PRAGMA index_info(${JSON.stringify(name)})`).all();
  const uniq = sq
    .prepare(`PRAGMA index_list(${JSON.stringify(tbl_name)})`)
    .all()
    .find((i) => i.name === name);
  if (!info.length) continue;
  const cols = info.map((i) => q(i.name)).join(', ');
  idxDdl.push(
    `CREATE ${uniq && uniq.unique ? 'UNIQUE ' : ''}INDEX IF NOT EXISTS ${q(name)} ON ${q(tbl_name)} (${cols});`
  );
}

(async () => {
  console.log(`SQLite: ${tables.length} tables, ${idxDdl.length} indexes, ${fkDdl.length} FKs`);
  if (DRY) {
    console.log([...ddl, ...fkDdl, ...idxDdl].join('\n\n'));
    return;
  }
  const pgc = new Client({
    connectionString: process.env.DATABASE_URL,
    ssl: { rejectUnauthorized: false },
  });
  await pgc.connect();
  try {
    if (DROP) {
      console.log('Dropping and recreating public schema…');
      await pgc.query('DROP SCHEMA public CASCADE; CREATE SCHEMA public;');
    }
    let done = 0;
    for (const stmt of ddl) {
      await pgc.query(stmt);
      if (++done % 25 === 0) console.log(`  tables: ${done}/${ddl.length}`);
    }
    console.log(`  tables: ${done}/${ddl.length} ✔`);
    let fkOk = 0, fkSkip = 0;
    for (const stmt of fkDdl) {
      try { await pgc.query(stmt); fkOk++; }
      catch (e) { fkSkip++; console.warn(`  FK skipped: ${e.message}`); }
    }
    console.log(`  foreign keys: ${fkOk} added, ${fkSkip} skipped`);
    let ixOk = 0, ixSkip = 0;
    for (const stmt of idxDdl) {
      try { await pgc.query(stmt); ixOk++; }
      catch (e) { ixSkip++; console.warn(`  index skipped: ${e.message}`); }
    }
    console.log(`  indexes: ${ixOk} added, ${ixSkip} skipped`);
    const { rows } = await pgc.query(
      "select count(*)::int as n from information_schema.tables where table_schema='public'"
    );
    console.log(`Postgres now has ${rows[0].n} tables in public schema.`);
  } finally {
    await pgc.end();
    sq.close();
  }
})().catch((e) => { console.error('FATAL:', e.message); process.exit(1); });
